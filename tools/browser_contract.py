"""Offline browser contract export. No runtime root argument or lifecycle/network."""

import argparse
import json
import sys
import tempfile
from pathlib import Path

# Importing the exporter never creates bytecode beside application sources.
sys.dont_write_bytecode = True

from pydantic import TypeAdapter

from harbor_helper.service import browser_contracts as b
from harbor_helper.service.api import create_app
from harbor_helper.service.attachment_contracts import AttachmentCreate, AttachmentPublish
from harbor_helper.service.contract_boundary import closed
from harbor_helper.service.machine import ErrorResponse


def schema():
    # create_app constructs files, so it only ever receives an owned temporary root.
    with tempfile.TemporaryDirectory(prefix="hh-contract-") as scratch:
        app = create_app(Path(scratch) / "state", start_scheduler=False)
        definitions = {}

        def describe(model, *, response=False):
            if response:
                model = closed(model)
            value = TypeAdapter(model).json_schema(ref_template="#/definitions/{model}")
            definitions.update(value.pop("$defs", {}))
            if isinstance(model, type) and hasattr(model, "model_fields"):
                definitions[model.__name__] = value
                return {"$ref": "#/definitions/" + model.__name__}
            return value

        routes = []
        for route in app.routes:
            name = getattr(getattr(route, "endpoint", None), "__name__", "")
            if name not in b.BROWSER:
                continue
            body = b.REQUESTS.get(name)
            if body is None:
                fields = [f for f in route.dependant.body_params if f.name == "body"]
                body = fields[0].field_info.annotation if fields else None
            metadata = (
                AttachmentCreate
                if name in {"create_attachment", "derive_attachment"}
                else AttachmentPublish
                if name == "publish_attachment"
                else None
            )
            routes.append(
                {
                    "operation": name,
                    "path": route.path.removeprefix("/api/v1"),
                    "method": next(iter(route.methods)),
                    "response": describe(b.BROWSER[name], response=True),
                    "request": describe(body) if body is not None else None,
                    "metadata": describe(metadata) if metadata else None,
                    "status": route.status_code or 200,
                    "projection": "browser/PAT" if name in b.MACHINE else "shared/session",
                    "media": "multipart/form-data" if metadata else "application/json",
                    "navigation": name == "download_report",
                }
            )
        error = describe(ErrorResponse)
        return {
            "definitions": definitions,
            "error": error,
            "routes": sorted(routes, key=lambda r: (r["path"], r["method"])),
        }


def ts(s):
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1]
    if "const" in s:
        return json.dumps(s["const"], ensure_ascii=False)
    if "enum" in s:
        return " | ".join(json.dumps(x) for x in s["enum"])
    for union in ("anyOf", "oneOf"):
        if union in s:
            return "(" + " | ".join(ts(x) for x in s[union]) + ")"
    if "allOf" in s:
        return "(" + " & ".join(ts(x) for x in s["allOf"]) + ")"
    kind = s.get("type")
    if kind == "array":
        return "Array<" + ts(s["items"]) + ">"
    if kind == "object" or "properties" in s:
        properties = s.get("properties", {})
        members = [
            json.dumps(k) + ("" if k in s.get("required", []) else "?") + ": " + ts(v)
            for k, v in properties.items()
        ]
        extra = s.get("additionalProperties")
        if extra:
            members.append(
                "[key: string]: " + (ts(extra) if isinstance(extra, dict) else "unknown")
            )
        return (
            "{ " + "; ".join(members) + " }"
            if members
            else "Record<string, never>"
            if extra is False
            else "Record<string, unknown>"
        )
    primitive = {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }
    if kind in primitive:
        return primitive[kind]
    if not s or set(s) <= {"title", "description", "default"}:
        return "unknown"  # Explicit unconstrained JSON (e.g. Pydantic JsonValue).
    raise ValueError(f"Unsupported JSON Schema: {s!r}")


def types(contract):
    lines = ["// Generated by tools/browser_contract.py. Do not edit."]
    for name, value in sorted(contract["definitions"].items()):
        lines.append(f"export type {name} = {ts(value)};")
    lines.append("export type ApiFailure = " + ts(contract["error"]) + ";")
    import re

    for method in ("GET", "POST", "PATCH", "PUT", "DELETE"):
        routes = [r for r in contract["routes"] if r["method"] == method and not r["navigation"]]
        routes.sort(key=lambda r: len(r["path"]), reverse=True)

        def key(r):
            return "`" + re.sub(r"\{[^}]+\}", "${string}", r["path"]) + "`"

        lines.append(f"export type {method}Path = " + " | ".join(key(r) for r in routes) + ";")
        lines.append(f"export type {method}<P extends {method}Path> =")
        for r in routes:
            req = (
                ts(r["metadata"] or r["request"])
                if r["metadata"] or r["request"]
                else "Record<string, never>"
            )
            lines.append(
                f"  P extends {key(r)} ? {{ request: {req}; response: {ts(r['response'])}; status: {r['status']}; media: {json.dumps(r['media'])} }} :"
            )
        lines.append("  never;")
        if method == "POST":
            for name, media in (
                ("JsonPostPath", "application/json"),
                ("UploadPath", "multipart/form-data"),
            ):
                lines.append(
                    f"export type {name} = "
                    + " | ".join(key(r) for r in routes if r["media"] == media)
                    + ";"
                )
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=Path("frontend/src/generated/contracts.ts"))
    parser.add_argument("--schema-output", type=Path, default=Path("frontend/contracts.json"))
    args = parser.parse_args()
    contract = schema()
    outputs = {
        args.output: types(contract),
        args.schema_output: json.dumps(contract, ensure_ascii=False, indent=2, sort_keys=True)
        + "\n",
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(
                    1, f"Contract drift: {path}; run uv run python tools/browser_contract.py\n"
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
