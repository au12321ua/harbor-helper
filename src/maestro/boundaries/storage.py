"""File storage half of the persistence boundary (the database is the other half).

Keys are opaque, generated by the platform, and never host paths.
"""

import hashlib
import os
import re
from pathlib import Path
from typing import Protocol

_KEY = re.compile(r"[a-z0-9_]+(?:/[a-z0-9_.-]+)+")


class ArtifactStore(Protocol):
    def put(self, key: str, data: bytes) -> tuple[str, int]: ...

    def get(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...

    def exists(self, key: str) -> bool: ...


def check_key(key: str) -> str:
    if not _KEY.fullmatch(key) or ".." in key.split("/"):
        raise ValueError(f"invalid storage key: {key!r}")
    return key


class LocalArtifactStore:
    """Write to a temporary file, fsync, then rename: no partially visible files."""

    def __init__(self, root: Path):
        self.root = root

    def _path(self, key: str) -> Path:
        return self.root / check_key(key)

    def put(self, key: str, data: bytes) -> tuple[str, int]:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
        with open(temporary, "wb") as file:
            file.write(data)
            file.flush()
            os.fsync(file.fileno())
        os.replace(temporary, path)
        return "sha256:" + hashlib.sha256(data).hexdigest(), len(data)

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()
