import { test, fixture, user } from "../../support/fixture";
import { expect } from "@playwright/test";
import type { Requests, RecycleEvent, DatasetEntry } from "../../../src/api";

test("request management separates recycle, restore and confirmed permanent deletion", async ({ page }) => {
  await fixture(page);
  let name = "Managed intention", recycled = false;
  let event: RecycleEvent | undefined;
  const record: Requests["requests"][number] = {id:"op-managed",group_id:"grp-managed",number:1,source_id:null,relation:"independent",name,creator_id:user.id,user_id:user.id,submitter:user.username,status:"rejected",run_id:null,created:1791460000,display_name:name};
  await page.route("**/api/v1/management/requests", r => r.fulfill({json:{requests:recycled?[]:[{...record,name,display_name:name}]}}));
  await page.route("**/api/v1/management/datasets", r => r.fulfill({json:{datasets:[]}}));
  await page.route("**/api/v1/management/recycle", async r => {
    if(r.request().method()==="GET") return r.fulfill({json:{items:event?[event]:[]}});
    expect(r.request().postDataJSON().items).toEqual([{kind:"request",object_id:record.id,expected:[]}]);
    recycled=true;
    event={id:"rec-current",kind:"request",object_id:record.id,owner_id:user.id,actor_id:user.id,created:1791460001,state:"recycled",cleanup:null,count:1};
    await r.fulfill({json:{results:[{kind:"request",object_id:record.id,event,error:null}]}});
  });
  await page.route("**/api/v1/management/groups/grp-managed", async r => {name=r.request().postDataJSON().name;await r.fulfill({json:{id:"grp-managed",name}});});
  await page.route("**/api/v1/management/recycle/preview", r => r.fulfill({json:{kind:"request",object_id:record.id,expected:[]}}));
  await page.route("**/api/v1/management/recycle/rec-current/restore", async r => {recycled=false;event={...event!,state:"restored"};await r.fulfill({json:event});});
  let purges=0;
  await page.route("**/api/v1/management/recycle/rec-current/purge", async r => {purges++;expect(r.request().headers()["idempotency-key"]).toBeTruthy();event={...event!,state:"purged",cleanup:"complete"};await r.fulfill({json:event});});
  await page.goto("/management");
  await page.getByLabel("组名（组创建者或管理员可改）").fill("Renamed group");
  await page.getByRole("button",{name:"保存组名"}).click();
  await expect(page.getByText("Renamed group / #1",{exact:true})).toBeVisible();
  page.on("dialog", d => d.accept());
  await page.getByLabel("选择请求 #1").check();
  await page.getByRole("button",{name:"将选中 1 项移入回收站"}).click();
  await page.getByRole("tab",{name:"回收站",exact:true}).click();
  await expect(page.getByText("request · op-managed",{exact:true})).toBeVisible();
  expect(purges).toBe(0);
  await page.getByRole("button",{name:"恢复",exact:true}).click();
  await page.getByRole("tab",{name:"请求组",exact:true}).click();
  await expect(page.getByText("Renamed group / #1",{exact:true})).toBeVisible();
  await page.getByLabel("选择请求 #1").check();
  await page.getByRole("button",{name:"将选中 1 项移入回收站"}).click();
  await page.getByRole("tab",{name:"回收站",exact:true}).click();
  await page.getByRole("button",{name:"永久删除",exact:true}).click();
  expect(purges).toBe(0);
  await page.getByRole("button",{name:"确认永久删除此回收事件"}).click();
  await expect(page.getByText(/purged · 1 项 · complete/)).toBeVisible();
  expect(purges).toBe(1);
  await page.screenshot({path:test.info().outputPath("management-recycle.png"),fullPage:true});
});

test("administrator selects a remote version then previews and confirms its digest", async ({page}) => {
  await fixture(page);
  const digest="sha256:"+"a".repeat(64);
  const dataset: DatasetEntry={id:"ds",source:"team/data",name:"Versioned",default_version:null,auto_named:0,versions:[],needs_merge:false};
  await page.route("**/api/v1/management/requests",r=>r.fulfill({json:{requests:[]}}));
  await page.route("**/api/v1/management/recycle",r=>r.fulfill({json:{items:[]}}));
  await page.route("**/api/v1/management/datasets",r=>r.fulfill({json:{datasets:[dataset]}}));
  await page.route("**/api/v1/management/datasets/ds/versions",r=>r.fulfill({json:{package:"team/data",versions:[{revision:8,digest,tags:["stable"],published:""}],truncated:true,possibly_incomplete:false,limit:200}}));
  await page.route("**/api/v1/management/datasets/ds/preview",r=>{expect(r.request().postDataJSON()).toEqual({digest});return r.fulfill({json:{id:"preview-fixed",dataset_id:"ds",resolved:"team/data@"+digest,tasks:[],listed:true}})});
  let confirmed=false;
  await page.route("**/api/v1/management/datasets/confirm",r=>{confirmed=true;expect(r.request().postDataJSON()).toEqual({preview_id:"preview-fixed"});return r.fulfill({json:{confirmed:true,resolved:"team/data@"+digest}})});
  await page.goto("/management");
  await page.getByRole("tab",{name:"数据集版本",exact:true}).click();
  await page.getByRole("button",{name:"查询远端可选版本"}).click();
  await expect(page.getByText("最近 200 个未撤回版本 · 已截断")).toBeVisible();
  await page.getByLabel("手选来源版本").selectOption(digest);
  await page.getByRole("button",{name:"预览固定摘要"}).click();
  await expect(page.getByText("固定来源：team/data@"+digest,{exact:false})).toBeVisible();
  expect(confirmed).toBe(false);
  await page.getByRole("button",{name:"确认纳入此版本"}).click();
  await expect(page.getByRole("button",{name:"确认纳入此版本"})).toHaveCount(0);
  expect(confirmed).toBe(true);
});
